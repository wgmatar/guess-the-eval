#!/usr/bin/env python3
"""Download the Cburnett chess pieces and write them as SVG symbols to src/ui/pieces.ts.

The shapes come from lichess-org/lila (public/piece/cburnett), whose path data is
identical to the Wikimedia Commons originals by Colin M.L. Burnett. Only the two colour
tokens are changed, to the app's ivory and near-black; nothing else is touched.

    python3 tools/fetch_pieces.py
"""

import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ui" / "pieces.ts"
BASE = "https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/cburnett"
USER_AGENT = "guess-the-eval-tools/1.0 (offline asset generator)"
# lila draws the highlight lines on black pieces in #ececec where the originals used white.
TONES = {"#000": "#161513", "#fff": "#F9F6F0", "#ececec": "#F9F6F0"}

HEADER = """\
// GENERATED by tools/fetch_pieces.py. Do not edit by hand.
//
// Chess piece artwork by Colin M.L. Burnett ("Cburnett"), from Wikimedia Commons via
// lichess-org/lila, used under the BSD 3-Clause licence (see LICENSES.md).
// Copyright (c) 2006, Colin M.L. Burnett. All rights reserved.
// Only the colour tokens are substituted; the shapes are unchanged.
"""


def fetch(name: str) -> str:
    request = urllib.request.Request(f"{BASE}/{name}.svg", headers={"User-Agent": USER_AGENT})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read().decode("utf-8")
        except Exception as error:  # noqa: BLE001 - network hiccups are retried
            wait = 2 * 3 ** attempt
            print(f"{name}: {error}; retrying in {wait}s", file=sys.stderr)
            time.sleep(wait)
    raise SystemExit(f"could not fetch {name}")


def symbol(name: str, svg: str) -> str:
    match = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not match:
        raise SystemExit(f"{name}: no <svg> element")
    inner = match.group(1).strip()
    for old, new in TONES.items():
        inner = re.sub(re.escape(old) + r'(?![0-9a-fA-F])', new, inner)
    return f'<symbol id="p-{name}" viewBox="0 0 45 45">{inner}</symbol>'


def main():
    symbols = []
    for colour in "wb":
        for kind in "KQRBNP":
            name = colour + kind
            symbols.append(symbol(name, fetch(name)))
            time.sleep(0.5)
    body = "\n".join(f"  {s!r} +" for s in symbols).rstrip(" +")
    OUT.write_text(f"{HEADER}\nexport const PIECE_SYMBOLS =\n{body};\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
