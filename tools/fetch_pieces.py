#!/usr/bin/env python3
"""Download the Cburnett chess pieces and write them as SVG symbols to src/ui/pieces.ts.

The shapes come from lichess-org/lila (public/piece/cburnett), whose path data is identical to
the Wikimedia Commons originals by Colin M.L. Burnett. The colour tokens are changed to the app's
ivory and near-black; the shapes are not touched.

Each black piece also gets a `-rim` variant: the same shapes in ivory, stroked a little wider,
drawn beneath the piece. Black pieces on dark squares use it so they do not sink into the square.
It is plain SVG rather than a filter, because browsers draw filters on <use> unreliably (a failed
filter hides the piece altogether).

    python3 tools/fetch_pieces.py
"""

import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ui" / "pieces.ts"
BASE = "https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/cburnett"
USER_AGENT = "guess-the-eval-tools/1.0 (offline asset generator)"
IVORY = "#F9F6F0"
# lila draws the highlight lines on black pieces in #ececec where the originals used white.
TONES = {"#000": "#161513", "#fff": IVORY, "#ececec": IVORY}
BASE_STROKE = 1.5
# Extra stroke width of the rim, in the 45-unit design square: about one unit each side.
RIM_EXTRA = 2.0

HEADER = """\
// GENERATED by tools/fetch_pieces.py. Do not edit by hand.
//
// Chess piece artwork by Colin M.L. Burnett ("Cburnett"), from Wikimedia Commons via
// lichess-org/lila, used under the BSD 3-Clause licence (see LICENSES.md).
// Copyright (c) 2006, Colin M.L. Burnett. All rights reserved.
// Only the colour tokens are substituted; the shapes are unchanged. The `-rim` symbols draw the
// same shapes in ivory beneath a black piece, for black pieces on dark squares.
"""


def fetch(name: str) -> str:
    request = urllib.request.Request(f"{BASE}/{name}.svg", headers={"User-Agent": USER_AGENT})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read().decode("utf-8")
        except Exception as error:  # noqa: BLE001 - network hiccups are retried
            wait = 2 * 3 ** attempt
            print(f"{name}: {error}; retrying in {wait}s", file=sys.stderr)
            time.sleep(wait)
    raise SystemExit(f"could not fetch {name}")


def inner_markup(name: str, svg: str) -> str:
    match = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not match:
        raise SystemExit(f"{name}: no <svg> element")
    inner = match.group(1).strip()
    if "style=" in inner:
        raise SystemExit(f"{name}: inline style attributes are not handled")
    for old, new in TONES.items():
        inner = re.sub(re.escape(old) + r"(?![0-9a-fA-F])", new, inner)
    return inner


def halo(inner: str) -> str:
    """The same shapes with every fill and stroke in ivory and every stroke wider."""
    out = re.sub(r'fill="(?!none")[^"]*"', f'fill="{IVORY}"', inner)
    out = re.sub(r'stroke="(?!none")[^"]*"', f'stroke="{IVORY}"', out)
    return re.sub(r'stroke-width="([\d.]+)"',
                  lambda m: f'stroke-width="{float(m.group(1)) + RIM_EXTRA:g}"', out)


def main():
    symbols = []
    for colour in "wb":
        for kind in "KQRBNP":
            name = colour + kind
            inner = inner_markup(name, fetch(name))
            symbols.append(f'<symbol id="p-{name}" viewBox="0 0 45 45">{inner}</symbol>')
            if colour == "b":
                rim = (f'<g fill="{IVORY}" stroke="{IVORY}" stroke-width="{BASE_STROKE + RIM_EXTRA:g}" '
                       f'stroke-linecap="round" stroke-linejoin="round">{halo(inner)}</g>')
                symbols.append(f'<symbol id="p-{name}-rim" viewBox="0 0 45 45">{rim}{inner}</symbol>')
            time.sleep(0.5)
    body = "\n".join(f"  {s!r} +" for s in symbols).rstrip(" +")
    OUT.write_text(f"{HEADER}\nexport const PIECE_SYMBOLS =\n{body};\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes, {len(symbols)} symbols)",
          file=sys.stderr)


if __name__ == "__main__":
    main()
